// Downloads the photos listed in scripts/image-sources.json from Wikimedia Commons, crops each to the
// exact size in scripts/image-specs.mjs, strips metadata, and writes it to public/images/.
//   node scripts/fetch-images.mjs [file-name ...]     (no arguments = every entry)
// Also regenerates src/content/image-credits.ts, which the gallery page shows as photo credits.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";
import { imageSpecs } from "./image-specs.mjs";

const root = process.cwd();
const sources = JSON.parse(readFileSync(join(root, "scripts/image-sources.json"), "utf8"));
const UA = "DeepakTourTravelSite/1.0 (https://github.com/) node-fetch";
const only = process.argv.slice(2);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const LICENSE_URL = (l) => {
  const m = /CC BY(-SA)? ([\d.]+)/.exec(l);
  return m ? `https://creativecommons.org/licenses/by${m[1] ? "-sa" : ""}/${m[2]}/` : "https://creativecommons.org/publicdomain/zero/1.0/";
};

async function download(title, width) {
  const url = `https://commons.wikimedia.org/wiki/Special:FilePath/${encodeURIComponent(title.replace(/ /g, "_"))}?width=${width}`;
  for (let attempt = 0; attempt < 5; attempt++) {
    const r = await fetch(url, { headers: { "User-Agent": UA }, redirect: "follow" });
    if (r.ok) return Buffer.from(await r.arrayBuffer());
    await sleep(2000 * (attempt + 1));
  }
  throw new Error(`download failed: ${title}`);
}

for (const spec of imageSpecs) {
  const src = sources[spec.file];
  if (!src || (only.length && !only.includes(spec.file))) continue;
  // Optional "crop" (fractions of the source) frames the subject before the final resize.
  const crop = src.crop ?? { left: 0, top: 0, width: 1, height: 1 };
  const scale = Math.max(spec.width / (src.width * crop.width), spec.height / (src.height * crop.height));
  const reqWidth = Math.min(src.width, Math.ceil(src.width * scale));
  const buf = await download(src.title, reqWidth);
  const meta = await sharp(buf).metadata();
  let img = sharp(buf).rotate();
  if (src.crop) {
    img = sharp(await img.extract({
      left: Math.round(meta.width * crop.left),
      top: Math.round(meta.height * crop.top),
      width: Math.round(meta.width * crop.width),
      height: Math.round(meta.height * crop.height),
    }).toBuffer());
  }
  await img
    .resize(spec.width, spec.height, { fit: "cover", position: sharp.strategy.attention })
    .jpeg({ quality: 78, mozjpeg: true })
    .toFile(join(root, "public/images", spec.file));
  console.log("ok", spec.file, `${reqWidth}px source`);
  await sleep(600);
}

const credits = Object.entries(sources).map(([file, s]) => ({
  file,
  title: s.title,
  author: s.author,
  license: s.license,
  licenseUrl: LICENSE_URL(s.license),
  source: s.page,
}));
writeFileSync(
  join(root, "src/content/image-credits.ts"),
  `// Generated by scripts/fetch-images.mjs. Delete an entry when you replace that photo with your own.\nexport type ImageCredit = { file: string; title: string; author: string; license: string; licenseUrl: string; source: string };\n\nexport const imageCredits: ImageCredit[] = ${JSON.stringify(credits, null, 2)};\n`,
);
